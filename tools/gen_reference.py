#!/usr/bin/env python3
"""gen_reference.py — write docs/reference/{cli,settings}.md from the code that defines them.

Both references used to be copied out of the code by hand (a command synopsis in ARCHITECTURE.md, the key
list in the README), and a copy drifts the day an option is added. They are generated instead (fleet rule
UPS-DOC-05): the CLI reference from the typer app's own click objects (ocrmd/cli.py), the settings reference
from the `Settings` model (ocrmd/config.py) — its fields, types and defaults — plus the comments written
beside each field, which is where this repo keeps the measurement behind a default.

  python3 tools/gen_reference.py --write   rewrite both files
  python3 tools/gen_reference.py --check   exit 1 if either is stale (tests/test_reference_docs.py runs this)

Exit status 2 means the package cannot be imported here (ocrmd is not installed); the test skips on it.

The CLI's defaults are read from the *loaded* settings at import time (`typer.Option(S.focus)`), so they
would otherwise carry whatever ocrmd.toml, .env or OCRMD_* the machine running this has. The generator
therefore drops OCRMD_* and USER from its environment, points OCRMD_ROOT and HOME at an empty directory, and swaps
`ocrmd.config.settings` for a pure-defaults `Settings` before `ocrmd.cli` is imported.
"""
from __future__ import annotations
import argparse, ast, atexit, inspect, io, json, os, re, shutil, sys, tempfile, tokenize
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CLI_DOC = REPO / "docs" / "reference" / "cli.md"
SETTINGS_DOC = REPO / "docs" / "reference" / "settings.md"
CONFIG_SRC = REPO / "ocrmd" / "config.py"
COMMAND = "python3 tools/gen_reference.py --write"
HEADER = f"<!-- GENERATED by {COMMAND} — do not edit by hand -->"
SECTION_RE = re.compile(r"^-{3}\s*(.+?)\s*-{3,}$")   # `# --- webcam auto-shutter ------`
HIDDEN = {"install_completion", "show_completion"}   # typer's own; named once in the intro instead


def prose(text: str) -> str:
    """Source text as Markdown: one line, `<` and `>` escaped outside code spans so `<root>` stays visible."""
    parts = re.split(r"(`[^`]*`)", re.sub(r"\s+", " ", text or "").strip())
    return "".join(x if x.startswith("`") else x.replace("<", "&lt;").replace(">", "&gt;") for x in parts)


def cell(text: str) -> str:
    """One table cell: `prose`, with pipes escaped (GFM honours `\\|` inside code spans too)."""
    return prose(text).replace("|", "\\|") or "—"


def paragraphs(text: str) -> list[str]:
    """A docstring as Markdown paragraphs: one per line, the source's soft wrapping joined."""
    return [prose(p) for p in re.split(r"\n\s*\n", inspect.cleandoc(text or "")) if p.strip()]


def first_sentence(text: str) -> str:
    """The docstring's first sentence, not fooled by `e.g.` or `i.e.`."""
    paras = paragraphs(text)
    if not paras:
        return ""
    for m in re.finditer(r"[.!?](?=\s|$)", paras[0]):
        if not re.search(r"\b(e\.g|i\.e|vs)\.$", paras[0][:m.end()]):
            return paras[0][:m.end()]
    return paras[0]


# --- the CLI ---------------------------------------------------------------------------------------
def _load_cli():
    """Import the typer app against pure defaults (see the module docstring for why)."""
    for k in [k for k in os.environ if k.startswith("OCRMD_")]:
        del os.environ[k]
    os.environ.pop("USER", None)   # `review --who` defaults to $USER: "runner" on CI, the login locally
    empty = tempfile.mkdtemp(prefix="ocrmd-ref-")
    atexit.register(shutil.rmtree, empty, True)
    os.environ["OCRMD_ROOT"] = os.environ["HOME"] = empty
    import ocrmd.config as config
    config.settings = config.Settings(root=Path(empty))
    import click, typer
    from ocrmd.cli import app
    return click, typer.main.get_command(app), config


def _opt_names(p) -> str:
    """`--doc`; `--page`, `-p`; `--admit` / `--no-admit` for an on/off pair."""
    sep = " / " if p.secondary_opts else ", "
    return sep.join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])


def _opt_type(p) -> str:
    if getattr(p, "is_flag", False) and not p.secondary_opts:
        return "flag"
    if getattr(p, "is_flag", False):
        return "switch"
    name = {"str": "text", "text": "text", "int": "integer", "integer": "integer", "float": "number",
            "boolean": "switch", "path": "path"}.get(p.type.name, p.type.name)
    return name + (", repeatable" if getattr(p, "multiple", False) else "")


def _opt_default(p) -> str:
    if p.required:
        return "**required**"
    d = p.default
    if d is None or d == [] or d == ():
        return "—"
    if d == "":
        return '`""`'
    if isinstance(d, bool):
        if p.secondary_opts:
            return f"`{(p.opts if d else p.secondary_opts)[0]}`"
        return "on" if d else "off"
    return f"`{d}`"


def _options_table(params) -> list[str]:
    rows = ["| Option | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for p in params:
        rows.append(f"| {_opt_names(p)} | {_opt_type(p)} | {_opt_default(p)} | {cell(getattr(p, 'help', '') or '')} |")
    return rows


def _usage(name: str, cmd) -> str:
    args = []
    for p in cmd.params:
        if p.param_type_name == "argument":
            meta = p.name.upper() + ("..." if p.nargs == -1 else "")
            args.append(meta if p.required else f"[{meta}]")
    opts = [p for p in cmd.params if p.param_type_name == "option"]
    return " ".join(["ocrmd", name] + (["[OPTIONS]"] if opts else []) + args)


def render_cli(click, group) -> str:
    ctx = click.Context(group, info_name="ocrmd")
    names = group.list_commands(ctx)
    out = [HEADER, "# CLI reference", "",
           "> Every `ocrmd` command, argument and option with its default — read from the typer app in "
           "`ocrmd/cli.py`, so it cannot drift from the code.", "",
           "Run a command as `ocrmd <command>` (the `[project.scripts]` entry point) or `python -m ocrmd <command>`; "
           "`ocrmd <command> --help` prints the same options. Defaults shown are the built-in ones: several "
           "(`--camera`, `--focus`, `--provider`, `--model`, `--admit`, `--focus-bracket`) follow the "
           "[settings](settings.md) when `ocrmd.toml` or an `OCRMD_*` variable changes them. Typer also adds "
           "`--install-completion` and `--show-completion` to the top level.", "",
           "## Global options", "", "Given before the command: `ocrmd --debug verify`.", ""]
    out += _options_table([p for p in group.params if p.name not in HIDDEN]) + [""]
    out += ["## Commands", "", "| Command | What it does |", "| --- | --- |"]
    for n in names:
        out.append(f"| [`{n}`](#{n}) | {cell(first_sentence(group.get_command(ctx, n).help or ''))} |")
    out.append("")
    for n in names:
        cmd = group.get_command(ctx, n)
        out += [f"## `{n}`", ""]
        for para in paragraphs(cmd.help or ""):
            out += [para, ""]
        out += ["```text", _usage(n, cmd), "```", ""]
        arguments = [p for p in cmd.params if p.param_type_name == "argument"]
        if arguments:
            out += ["| Argument | Type | Description |", "| --- | --- | --- |"]
            out += [f"| `{p.name.upper()}` | {_opt_type(p)}{', one or more' if p.nargs == -1 else ''} | "
                    f"{cell(getattr(p, 'help', '') or '')} |" for p in arguments]
            out.append("")
        options = [p for p in cmd.params if p.param_type_name == "option"]
        if options:
            out += _options_table(options) + [""]
    return "\n".join(out).rstrip() + "\n"


# --- the settings -----------------------------------------------------------------------------------
def _comments(src: str) -> dict[int, tuple[str, bool]]:
    """line number -> (comment text, is the whole line a comment)."""
    lines, out = src.splitlines(), {}
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT:
            row, col = tok.start
            out[row] = (tok.string.lstrip("#").strip(), not lines[row - 1][:col].strip())
    return out


def _model_items(src: str, cls_name: str):
    """Yield ("section", title) | ("note", text) | ("field", name, annotation, trailing, block) in source order."""
    tree, comments = ast.parse(src), _comments(src)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == cls_name)
    prev = cls.lineno
    for stmt in cls.body:
        if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
            prev = stmt.end_lineno
            continue
        block: list[str] = []
        for row in range(prev + 1, stmt.lineno):
            text, full = comments.get(row, ("", False))
            if not full:
                continue
            m = SECTION_RE.match(text)
            if m:
                if block:
                    yield ("note", " ".join(block))
                block = []
                yield ("section", m.group(1))
            elif text:
                block.append(text)
        trailing = next((t for r, (t, full) in comments.items() if r == stmt.end_lineno and not full), "")
        yield ("field", stmt.target.id, ast.get_source_segment(src, stmt.annotation), trailing, " ".join(block))
        prev = stmt.end_lineno


def _title(text: str) -> str:
    """A `# --- section ---` comment as a heading: `ocr` -> `OCR`, `webcam auto-shutter` -> `Webcam auto-shutter`."""
    return text.upper() if len(text) <= 3 else text[0].upper() + text[1:]


def _sentence(text: str) -> str:
    """A block comment as a paragraph, capitalised the way a sentence would be."""
    return prose(text[:1].upper() + text[1:])


def _toml(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, (int, float)):
        return f"`{value!r}`"
    if isinstance(value, (str, list, dict)):
        return f"`{json.dumps(value, ensure_ascii=False)}`"
    return f"`{value}`"


def _settings_tables(model, src: str, cls_name: str, env: bool, special: dict[str, str]) -> list[str]:
    head = ["| Setting | Environment variable | Type | Default | Notes |", "| --- | --- | --- | --- | --- |"] if env \
        else ["| Key | Type | Default | Notes |", "| --- | --- | --- | --- |"]
    out, table_open, seen = [], False, []
    for item in _model_items(src, cls_name):
        if item[0] == "section":
            out += [""] if table_open else []
            out += [f"### {_title(item[1])}", ""]
            table_open = False
        elif item[0] == "note":
            out += ([""] if table_open else []) + [_sentence(item[1]), ""]
            table_open = False
        else:
            _, name, annotation, trailing, block = item
            seen.append(name)
            if block and trailing:   # a comment above a field that has its own: it explains a group
                out += ([""] if table_open else []) + [_sentence(block), ""]
                table_open, block = False, ""
            if not table_open:
                out += head
                table_open = True
            field = model.model_fields[name]
            default = special.get(name) or ("**required**" if field.is_required() else _toml(field.default))
            notes = cell(trailing or block)
            row = [f"`{name}`"] + ([f"`OCRMD_{name.upper()}`"] if env else []) + [f"`{cell(annotation)}`", default, notes]
            out.append("| " + " | ".join(row) + " |")
    missing = set(model.model_fields) ^ set(seen)
    if missing:
        raise SystemExit(f"gen_reference: {cls_name} fields and the parsed source disagree: {sorted(missing)}")
    return out


def render_settings(config) -> str:
    src = CONFIG_SRC.read_text(encoding="utf-8")
    out = [HEADER, "# Settings reference", "",
           "> Every `Settings` field in `ocrmd/config.py` — its `OCRMD_*` environment variable, type, built-in "
           "default and the note written beside it in the source.", ""]
    out += _docstring_blocks(config.__doc__)
    out += ["Values are validated on load and an invalid one fails fast, naming the key. In the environment a "
            "list may be comma-separated (`OCRMD_OCR_ENGINES=apple_vision,rapidocr`) and `OCRMD_SINKS` takes JSON. "
            "[`ocrmd.example.toml`](../../ocrmd.example.toml) is a commented starting file; `ocrmd doctor` prints the "
            "effective values.", "", "## Settings", ""]
    out += _settings_tables(config.Settings, src, "Settings", True,
                            {"root": "`OCRMD_ROOT`, else the project directory"})
    out += ["", "## `[[sinks]]` entries", "",
            "Each destination in `sinks` (a `[[sinks]]` table in `ocrmd.toml`, or one object in the `OCRMD_SINKS` "
            "JSON list) takes these keys; the receiver contract is in `ocrmd/sinks.py`.", ""]
    out += _settings_tables(config.SinkConfig, src, "SinkConfig", False, {})
    return "\n".join(out).rstrip() + "\n"


def _docstring_blocks(doc: str) -> list[str]:
    """The config module docstring after its title line: list items kept as items, prose joined."""
    out: list[str] = []
    for block in re.split(r"\n\s*\n", inspect.cleandoc(doc).split("\n", 1)[1]):
        lines = [ln.strip() for ln in block.strip().splitlines() if ln.strip()]
        items = [prose(ln) for ln in lines if re.match(r"^\d+\.\s", ln)]
        text = [ln for ln in lines if not re.match(r"^\d+\.\s", ln)]
        if items:
            out += ([prose(" ".join(text)), ""] if text else []) + items + [""]
        elif lines:
            out += [prose(" ".join(lines)), ""]
    return out


# --- driver -------------------------------------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    sys.path.insert(0, str(REPO))
    try:
        click, group, config = _load_cli()
    except ImportError as e:   # ocrmd or one of its dependencies is not installed in this interpreter
        print(f"gen_reference: cannot import ocrmd here ({e}); install it with `pip install -e .`", file=sys.stderr)
        return 2
    docs = {CLI_DOC: render_cli(click, group), SETTINGS_DOC: render_settings(config)}
    stale = [p for p, text in docs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"{p.relative_to(REPO)} is stale: run `{COMMAND}`", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(docs[p], encoding="utf-8")
        print(f"wrote {p.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
